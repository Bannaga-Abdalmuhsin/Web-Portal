router.post("/seed", async (req, res) => {
  try {
    const results: Record<string, number> = {};

    // Check existing data
    const [siteCount] = await db.select({ value: count() }).from(sitesTable);
    if (siteCount.value > 0) {
      return res.json({ message: "Already seeded", sites: siteCount.value });
    }

    // Seed admins
    for (const admin of SEED_ADMINS) {
      await db.insert(adminsTable).values(admin).onConflictDoNothing();
    }
    results.admins = SEED_ADMINS.length;

    // Seed sites in batches of 50
    for (let i = 0; i < SEED_SITES.length; i += 50) {
      const batch = SEED_SITES.slice(i, i + 50);
      await db.insert(sitesTable).values(batch.map((s: any) => ({
        name: s.name,
        district: s.district || "",
        city: s.city || "",
        project: s.project || "stc COW",
        cowStatus: s.cow_status || "ON-AIR",
        active: s.active !== false,
        currentLiters: s.current_liters || 0,
        dailyVirtual: s.daily_virtual || 0,
        region: s.region || "",
        siteLabel: s.site_label || "",
        lat: s.lat || null,
        lng: s.lng || null,
        nextFuelingPlan: s.next_fueling_plan || "",
        lastFuelingDate: s.last_fueling_date || "",
        lastFuelingQty: s.last_fueling_qty || null,
      }))).onConflictDoNothing();
    }
    results.sites = SEED_SITES.length;

    // Seed missions
    for (let i = 0; i < SEED_MISSIONS.length; i += 20) {
      const batch = SEED_MISSIONS.slice(i, i + 20);
      await db.insert(missionsTable).values(batch.map((m: any) => ({
        missionId: m.missionId,
        siteName: m.siteName,
        generator: m.generator,
        project: m.project,
        city: m.city,
        quantityAddedLastTask: m.quantityAddedLastTask,
        notes: m.notes,
        missionStatus: "Creation",
        createdBy: "System",
      }))).onConflictDoNothing();
    }
    results.missions = SEED_MISSIONS.length;

    // Seed drivers
    for (const driver of SEED_DRIVERS) {
      await db.insert(driversTable).values(driver).onConflictDoNothing();
    }
    results.drivers = SEED_DRIVERS.length;

    res.json({ success: true, seeded: results });
  } catch (err) {
    req.log.error({ err }, "Seed failed");
    res.status(500).json({ error: "Seed failed", detail: String(err) });
  }
});

